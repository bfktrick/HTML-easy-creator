export const messages: Record<'es' | 'en', Record<MessageKey, string>> = { es, en };

/** Replaces {name} with vars.name; unknown placeholders stay as they are. */
export function format(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

function isMessageKey(key: string): key is MessageKey {
  return key in es;
}

/** Message for an error code from the API (or for anything thrown). */
export function errorKey(error: unknown): MessageKey {
  const code =
    typeof error === 'string'
      ? error
      : typeof error === 'object' && error !== null && 'code' in error && typeof error.code === 'string'
        ? error.code
        : '';
  const key = `error.${code}`;
  return code && isMessageKey(key) ? key : 'error.generic';
}
